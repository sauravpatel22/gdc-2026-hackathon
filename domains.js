export function isKnownGamblingDomain(hostname) {
  if (!hostname) return false;
  const host = String(hostname).toLowerCase().replace(/\.$/, "");
  return GAMBLING_DOMAINS.some(
    (domain) => host === domain || host.endsWith("." + domain)
  );
}
